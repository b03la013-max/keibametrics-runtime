"""Path filters for the acceptance workflows (Owner 2026-11-19 09:59「絞りましょう」).

An acceptance workflow should run on push/PR only when something it actually checks changes. Its trigger
paths are therefore DERIVED, not hand-written: every repo file named in the workflow's run steps, plus the
transitive closure of
  * Python imports (import / from-import of repo modules),
  * string literals that name a repo module ('runtime.foo') or an existing repo file / directory
    ('profiles/x.json', 'research/local_bvi') -- covers importlib and data files read by tests,
plus the paths already listed for pull_request and the workflow file itself.

  python tools/ci_paths.py --write <workflow.yml> ...   rewrite push.paths and pull_request.paths
  python tools/ci_paths.py --check <workflow.yml> ...   exit 1 if a required path is missing (used by tests)
"""
import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BEGIN, END = '# ci_paths:begin (generated by tools/ci_paths.py; do not edit by hand)', '# ci_paths:end'
FILE_RE = re.compile(r'(?<![\w./-])((?:runtime|tests|profiles|mapping|research|governance|tools|data)/[\w./*-]+)')


def _mod_file(mod):
    p = ROOT / Path(*mod.split('.'))
    for c in (p.with_suffix('.py'), p / '__init__.py'):
        if c.is_file():
            return c
    return None


def _refs(py):
    try:
        src = py.read_text(encoding='utf-8')
        tree = ast.parse(src)
    except (OSError, SyntaxError, UnicodeDecodeError):
        return set()
    out = set()
    for n in ast.walk(tree):
        mods = []
        if isinstance(n, ast.Import):
            mods = [a.name for a in n.names]
        elif isinstance(n, ast.ImportFrom) and n.module and not n.level:
            mods = [n.module] + [f'{n.module}.{a.name}' for a in n.names]
        elif isinstance(n, ast.ImportFrom) and n.level:          # relative import inside a package
            base = py.parent
            for _ in range(n.level - 1):
                base = base.parent
            pkg = '.'.join(base.relative_to(ROOT).parts)
            mods = [f'{pkg}.{n.module}' if n.module else pkg] + [f"{pkg}{'.' + n.module if n.module else ''}.{a.name}" for a in n.names]
        elif isinstance(n, ast.Constant) and isinstance(n.value, str):
            s = n.value
            if re.fullmatch(r'(?:runtime|tests|tools)(?:\.\w+)+', s):
                mods = [s]
            for m in FILE_RE.findall(s):
                out.add(m.rstrip('/.'))
        for m in mods:
            f = _mod_file(m)
            if f:
                out.add(str(f.relative_to(ROOT)))
    if 'sys.path' in src:                                      # scripts that import siblings by bare name
        for n in ast.walk(tree):
            if isinstance(n, (ast.Import, ast.ImportFrom)) and not getattr(n, 'level', 0):
                for a in ([x.name for x in n.names] if isinstance(n, ast.Import) else [n.module or '']):
                    c = py.parent / f'{a.split(".")[0]}.py'
                    if c.is_file():
                        out.add(str(c.relative_to(ROOT)))
    return out


def _existing(p):
    if '*' in p:
        return p
    q = ROOT / p
    if q.is_file():
        return p
    if q.is_dir():
        return p.rstrip('/') + '/**'
    return None


def required(wf):
    text = Path(wf).read_text(encoding='utf-8')
    body = text.split('\njobs:', 1)[1] if '\njobs:' in text else text
    seeds = {m.rstrip('/.') for m in FILE_RE.findall(body)}
    pr = re.search(r'pull_request:\s*\n(?:\s+branches:.*\n)?\s+paths:\s*\n((?:\s+- .*\n)+)', text)
    listed = set(re.findall(r"- '([^']+)'", pr[1])) if pr else set()
    seen, todo, out = set(), list(seeds | listed), set()
    while todo:
        p = todo.pop()
        e = _existing(p)
        if not e or e in seen:
            continue
        seen.add(e)
        out.add(e)
        if e.endswith('.py'):
            todo += sorted(_refs(ROOT / e))
    out.add(str(Path(wf).resolve().relative_to(ROOT)))
    return sorted(out)


def covered(path, patterns):
    for p in patterns:
        if p == path or (p.endswith('/**') and path.startswith(p[:-2])):
            return True
    return False


def current(wf):
    text = Path(wf).read_text(encoding='utf-8')
    blocks = re.findall(re.escape(BEGIN) + r'\n(.*?)' + re.escape(END), text, re.S)
    if len(blocks) != 2:                        # pull_request and push must both carry the list
        return None
    lists = [re.findall(r"- '([^']+)'", b) for b in blocks]
    return lists[0] if lists[0] == lists[1] else None


def write(wf):
    req = required(wf)
    block = '\n'.join(f"      - '{p}'" for p in req)
    paths = f"    paths:\n      {BEGIN}\n{block}\n      {END}\n"
    text = Path(wf).read_text(encoding='utf-8')
    head, jobs = text.split('\njobs:', 1)
    on = re.search(r'^on:\n(.*?)(?=^\S)', head + '\n', re.S | re.M)
    rest = [ln for ln in on[1].splitlines() if ln.strip()]
    others = []                               # keep every trigger except pull_request / push
    skip = False
    for ln in rest:
        if re.match(r'^  (pull_request|push):', ln):
            skip = True
            continue
        if re.match(r'^  \S', ln):
            skip = False
        if not skip:
            others.append(ln)
    new_on = ('on:\n  pull_request:\n    branches: [main]\n' + paths +
              '  push:\n    branches: [main]\n' + paths + ('\n'.join(others) + '\n' if others else ''))
    head = head[:on.start()] + new_on + head[on.end():]
    Path(wf).write_text(head.rstrip('\n') + '\n\njobs:' + jobs, encoding='utf-8')
    return req


def main():
    mode, wfs = sys.argv[1], sys.argv[2:]
    bad = 0
    for wf in wfs:
        if mode == '--write':
            print(wf, len(write(wf)), 'paths')
        else:
            have = current(wf) or []
            miss = [p for p in required(wf) if not covered(p, have)]
            if miss:
                bad = 1
                print(wf, 'MISSING', miss)
    sys.exit(bad)


if __name__ == '__main__':
    main()
