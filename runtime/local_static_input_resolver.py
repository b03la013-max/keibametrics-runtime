"""Locate existing LOCAL frozen input; never invent a Production ranking."""
from __future__ import annotations
import copy
from datetime import datetime
import json
from pathlib import Path
from runtime import formal_execution_orchestrator as o


def _time(value):
    stamp = datetime.fromisoformat(str(value).replace('Z', '+00:00'))
    if stamp.tzinfo is None:
        raise ValueError('STATIC_INPUT_TIMEZONE_REQUIRED')
    return stamp


def resolve(request, source, *, root=None):
    root = Path(root or o.ROOT)
    eid = request['execution_id']
    if not eid or Path(eid).name != eid or eid in {'.', '..'} or '\\' in eid:
        raise ValueError('STATIC_INPUT_EXECUTION_ID_INVALID')
    path = root/'runtime/formal_intents'/f'{eid}.json'
    if request.get('static_prediction'):
        candidate, mode, location = copy.deepcopy(request), 'EXPLICIT_FROZEN_STATIC', None
    elif path.is_file():
        candidate = json.loads(path.read_text())
        mode, location = 'CANONICAL_FORMAL_INTENT', str(path.relative_to(root))
    else:
        return None, {'status': 'MISSING_RACE_STATIC', 'input_mode': 'CHAT_OWNED_FROZEN_INPUT',
                      'searched_path': str(path.relative_to(root)), 'c2_owner_required': False,
                      'static_generation_executed': False, 'production_prediction_changed': False}
    if candidate.get('family_id') != 'LOCAL' or o.derive_execution_id(candidate) != eid or candidate.get('race_id') != request['race_id']:
        raise ValueError('STATIC_INPUT_RACE_OR_FAMILY_MISMATCH')
    for key in ('venue_id', 'race_date', 'race_no'):
        if str(candidate.get(key)).replace('/', '-') != str(request.get(key)).replace('/', '-'):
            raise ValueError('STATIC_INPUT_IDENTITY_MISMATCH:' + key)
    for key in ('prediction_cutoff', 'scheduled_post_at'):
        if _time(candidate.get(key)) != _time(request.get(key)):
            raise ValueError('STATIC_INPUT_TIME_BASIS_MISMATCH:' + key)
    candidate, _ = o.normalize_single_entry_intent(candidate)
    universe = {str(r['runner_id']) for r in source['artifact']['official_runner_universe']['runners']}
    ranking = [str(x) for x in candidate['static_prediction'].get('ranking') or []]
    if len(ranking) != len(universe) or set(ranking) != universe:
        raise ValueError('STATIC_INPUT_FULL_RUNNER_UNIVERSE_MISMATCH')
    if not set(candidate['static_prediction'].get('roles') or {}).issubset(universe):
        raise ValueError('STATIC_INPUT_ROLE_RUNNER_MISMATCH')
    for declared in (candidate.get('source_receipt_sha256'), candidate['static_prediction'].get('source_receipt_sha256')):
        if declared and declared != source['receipt_sha256']:
            raise ValueError('STATIC_INPUT_SIGNED_SOURCE_MISMATCH')
    return candidate, {'status': 'FROZEN_INPUT_LOCATED', 'input_mode': mode, 'path': location,
                       'c2_owner_required': False, 'static_generation_executed': False,
                       'production_prediction_changed': False}


def input_packet(request, source, resolution, *, generation_allowed):
    """Pass authenticated evidence to the existing chat/external input owner."""
    formal_template = copy.deepcopy(request)
    formal_template.pop('execution_phase', None)
    formal_template.pop('analysis_only', None)
    return {'schema': 'KM-LOCAL-STATIC-INPUT-PACKET-v1', 'request': formal_template,
            'source_receipt_sha256': source['receipt_sha256'],
            'source_snapshot_sha256': source['artifact']['source_snapshot_sha256'],
            'official_runner_universe': copy.deepcopy(source['artifact']['official_runner_universe']),
            'normalized_evidence': copy.deepcopy(source['artifact'].get('normalized_evidence')),
            'owner_resolution': resolution, 'static_generation_allowed': generation_allowed,
            'prediction_consumption_authorized': False, 'c2_owner_required': False,
            'instruction': 'Use the current LOCAL/Venue canon through the existing chat-owned frozen-input path. Do not promote a new model or use diagnostic indices as authorized prediction weights. Complete the original Formal Intent with result-blind ranking, roles, Pair/Third and context before the release deadline. No ranking is generated by this packet.'}
